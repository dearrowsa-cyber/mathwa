out_dir = os.path.join('public', 'docs')
os.makedirs(out_dir, exist_ok=True)

width, height = A4

def draw_arabic(c, text, x, y, font="Amiri", size=14):
    reshaped_text = arabic_reshaper.reshape(text)
    bidi_text = get_display(reshaped_text)
    c.setFont(font, size)
    # Right align calculation (approximate)
    text_width = c.stringWidth(bidi_text, font, size)
    c.drawString(width - x - text_width, y, bidi_text)

for doc in docs:
    pdf_path = os.path.join(out_dir, doc['filename'])
    print(f"Generating {pdf_path}...")
    c = canvas.Canvas(pdf_path, pagesize=A4)
    
    # Header
    draw_arabic(c, "جمعية مثوى الأهلية", 50, height - 60, size=20)
    draw_arabic(c, doc['title'], 50, height - 100, size=24)
    
    # Line
    c.line(50, height - 120, width - 50, height - 120)
    
    # Content
    y = height - 160
    for line in doc['content']:
        if y < 100:
            c.showPage()
            y = height - 80
        draw_arabic(c, line, 50, y, size=14)
        y -= 25
        
    # Footer
    c.line(50, 50, width - 50, 50)
    draw_arabic(c, "تم اعتماد هذه الوثيقة من قبل مجلس الإدارة - جمعية مثوى الأهلية (ترخيص رقم 1000827300)", 50, 30, size=10)
    
    c.save()

print("All PDFs generated successfully!")
