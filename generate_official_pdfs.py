W, H = A4

def ar(text):
    """Reshape and apply bidi for Arabic text."""
    return get_display(arabic_reshaper.reshape(text))

def draw_ar(c, text, x, y, font="Amiri", size=12, color=black, align="right"):
    """Draw Arabic text with proper alignment."""
    bidi = ar(text)
    c.setFont(font, size)
    c.setFillColor(color)
    tw = c.stringWidth(bidi, font, size)
    if align == "right":
        c.drawString(W - x - tw, y, bidi)
    elif align == "center":
        c.drawCentredString(W / 2, y, bidi)
    elif align == "left":
        c.drawString(x, y, bidi)
    return tw

def generate_qr(url, size=120):
    """Generate QR code image."""
    qr = qrcode.QRCode(version=1, box_size=10, border=1, error_correction=qrcode.constants.ERROR_CORRECT_H)
    qr.add_data(url)
    qr.make(fit=True)
    img = qr.make_image(fill_color="#1B6B3A", back_color="white")
    buf = BytesIO()
    img.save(buf, format='PNG')
    buf.seek(0)
    return ImageReader(buf)

def draw_page(c, doc, category):
    """Draw a single premium PDF page."""
    
    # ══════ BACKGROUND ══════
    c.setFillColor(BRAND_LIGHT_BG)
    c.rect(0, 0, W, H, fill=1, stroke=0)
    
    # ══════ TOP GREEN BAR ══════
    c.setFillColor(BRAND_GREEN)
    c.rect(0, H - 8, W, 8, fill=1, stroke=0)
    
    # ══════ GOLD ACCENT LINE ══════
    c.setFillColor(BRAND_GOLD)
    c.rect(0, H - 11, W, 3, fill=1, stroke=0)
    
    # ══════ HEADER SECTION ══════
    header_y = H - 130
    
    # ══════ HEADER: THREE ZONES (Left logo | Center name | Right logo) ══════
    # Zone 1: Mathwaa Logo - top left, height 80px
    LOGO_H = 80
    LOGO_TOP = H - 10 - LOGO_H  # y from bottom
    if os.path.exists(MATHWAA_LOGO):
        try:
            c.drawImage(MATHWAA_LOGO, 25, LOGO_TOP, width=80, height=LOGO_H, mask='auto', preserveAspectRatio=True)
        except:
            pass

    # Zone 2: NCNP Logo - top right, same height
    if os.path.exists(NCNP_LOGO):
        try:
            c.drawImage(NCNP_LOGO, W - 165, LOGO_TOP + 5, width=140, height=70, mask='auto', preserveAspectRatio=True)
        except:
            pass

    # Zone 3: Center text - association name
    name_center_y = H - 35
    draw_ar(c, "جمعية مثوى", 0, name_center_y, font="AmiriBold", size=18, color=BRAND_DARK_GREEN, align="center")
    draw_ar(c, "Mathwaa Charitable Association", 0, name_center_y - 18, font="Amiri", size=9, color=BRAND_GREEN, align="center")

    # ── Metadata block - BELOW logos, left-aligned, inside left zone ──
    meta_y = LOGO_TOP - 5
    draw_ar(c, "رقم الصادر: ED035413", 40, meta_y, size=8, color=HexColor('#555555'))
    draw_ar(c, "تاريخ الإصدار: 1447/06/06 هـ", 40, meta_y - 12, size=8, color=HexColor('#555555'))
    draw_ar(c, "رقم الترخيص: 1000827300", 40, meta_y - 24, size=8, color=HexColor('#555555'))

    header_y = LOGO_TOP - 38

    # ══════ DIVIDER LINE ══════
    c.setStrokeColor(BRAND_GOLD)
    c.setLineWidth(1.5)
    c.line(30, header_y, W - 30, header_y)

    # ══════ CATEGORY BADGE ══════
    cat_names = {"Policies": "السياسات", "Regulations": "اللوائح", "Reports": "التقارير", "Financials": "المالية"}
    cat_label = cat_names.get(category, category)
    badge_y = header_y - 22

    badge_text = ar(cat_label)
    c.setFont("AmiriBold", 10)
    btw = c.stringWidth(badge_text, "AmiriBold", 10)
    badge_x = W / 2 - btw / 2 - 12
    c.setFillColor(BRAND_GREEN)
    c.roundRect(badge_x, badge_y - 4, btw + 24, 20, 8, fill=1, stroke=0)
    c.setFillColor(white)
    c.drawCentredString(W / 2, badge_y, badge_text)

    # ══════ TITLE ══════
    title_y = badge_y - 36
    draw_ar(c, doc['title'], 0, title_y, font="AmiriBold", size=20, color=BRAND_DARK_GREEN, align="center")

    # Gold underline for title
    c.setStrokeColor(BRAND_GOLD)
    c.setLineWidth(2)
    title_bidi = ar(doc['title'])
    c.setFont("AmiriBold", 20)
    ttw = c.stringWidth(title_bidi, "AmiriBold", 20)
    c.line(W/2 - ttw/2, title_y - 4, W/2 + ttw/2, title_y - 4)

    # ══════ CONTENT ══════
    y = title_y - 35
    margin_right = 50
    margin_left = 50
    max_width = W - margin_right - margin_left

    for line in doc['content']:
        if y < 210:  # Leave room for footer
            break

        is_header = line.endswith(':') or line.startswith('الفصل') or line.startswith('أولاً') or line.startswith('ثانياً') or line.startswith('ثالثاً')

        if is_header:
            y -= 8
            draw_ar(c, line, margin_right, y, font="AmiriBold", size=12, color=BRAND_GREEN)
            y -= 20
        elif line.startswith('- ') or line.startswith('١') or line.startswith('٢') or line.startswith('٣') or line.startswith('٤') or line.startswith('٥') or line.startswith('٦'):
            words = line.split()
            current_line = []
            for word in words:
                current_line.append(word)
                test = " ".join(current_line)
                reshaped = ar(test)
                if c.stringWidth(reshaped, "Amiri", 11) > max_width - 15:
                    current_line.pop()
                    if current_line:
                        draw_ar(c, "  " + " ".join(current_line), margin_right, y, size=11, color=HexColor('#333333'))
                        y -= 17
                    current_line = [word]
            if current_line:
                draw_ar(c, "  " + " ".join(current_line), margin_right, y, size=11, color=HexColor('#333333'))
                y -= 17
        else:
            words = line.split()
            current_line = []
            for word in words:
                current_line.append(word)
                test = " ".join(current_line)
                reshaped = ar(test)
                if c.stringWidth(reshaped, "Amiri", 12) > max_width:
                    current_line.pop()
                    if current_line:
                        draw_ar(c, " ".join(current_line), margin_right, y, size=12, color=HexColor('#222222'))
                        y -= 19
                    current_line = [word]
            if current_line:
                draw_ar(c, " ".join(current_line), margin_right, y, size=12, color=HexColor('#222222'))
                y -= 19
        y -= 4

    # ══════ FOOTER SECTION ══════
    footer_top = 210

    # Gold separator line
    c.setStrokeColor(BRAND_GOLD)
    c.setLineWidth(1.5)
    c.line(30, footer_top, W - 30, footer_top)

    # ── Signature (Bottom Left) - LARGE ──
    SIG_W = 220
    SIG_H = 180
    if os.path.exists(SIGNATURE):
        try:
            c.drawImage(SIGNATURE, 15, 30, width=SIG_W, height=SIG_H, mask='auto', preserveAspectRatio=True)
        except:
            pass

    # ── Stamp (Bottom Right) - LARGE ──
    STAMP_SIZE = 170
    if os.path.exists(STAMP):
        try:
            c.drawImage(STAMP, W - STAMP_SIZE - 20, 40, width=STAMP_SIZE, height=STAMP_SIZE, mask='auto', preserveAspectRatio=True)
        except:
            pass

    # ── QR Code (Center Bottom) ──
    QR_SIZE = 90
    qr_url = f"https://mathwaa.org.sa/docs/{doc['filename']}"
    qr_img = generate_qr(qr_url, size=QR_SIZE)
    c.drawImage(qr_img, W/2 - QR_SIZE/2, 55, width=QR_SIZE, height=QR_SIZE)
    c.setFont("Amiri", 7)
    c.setFillColor(HexColor('#888888'))
    qr_label = ar("للتحقق من الوثيقة")
    qr_label_w = c.stringWidth(qr_label, "Amiri", 7)
    c.drawString(W/2 - qr_label_w/2, 44, qr_label)

    # ══════ BOTTOM BAR ══════
    c.setFillColor(BRAND_GREEN)
    c.rect(0, 0, W, 12, fill=1, stroke=0)
    c.setFillColor(BRAND_GOLD)
    c.rect(0, 12, W, 3, fill=1, stroke=0)


